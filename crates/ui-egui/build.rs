//! Embeds optional extra syntaxes: every `assets/syntax/<token>.packdump` becomes a static in the binary, where
//! `<token>` is the fenced-block language (```token). The folder is not part of the repository (third-party
//! grammars; see `examples/mksyntax.rs` for how to build a dump). Without dumps nothing is embedded and the
//! lookup code is compiled out entirely.
//!
//! Rebuild quirks: cargo notices a *removed* dump but not one that *appears* — after adding the first dump, force
//! one rebuild with `touch crates/ui-egui/build.rs`. If diagnostics ever point at a stale
//! `target/.../out/bundled_syntaxes.rs` (an older build-script run cached by cargo or the editor), regenerate
//! with `cargo clean -p iron-sheets-ui-egui`; restarting rust-analyzer clears its cached build-script
//! diagnostics.
use std::{fs, path::Path};

fn main() {
    let dir = Path::new("assets/syntax");
    let mut dumps: Vec<String> = Vec::new();
    if let Ok(entries) = fs::read_dir(dir) {
        for e in entries.flatten() {
            let p = e.path();
            if p.extension().is_some_and(|x| x == "packdump") {
                let token = p.file_stem().and_then(|s| s.to_str()).expect("utf-8 dump name").to_owned();
                println!("cargo:rerun-if-changed={}", p.display());
                dumps.push(token);
            }
        }
    }
    if dumps.is_empty() {
        // Cargo does not notice files that appear later; `touch build.rs` after adding the first dump.
        println!("cargo:rerun-if-changed=assets/syntax");
        return;
    }
    dumps.sort();
    let mut src =
        String::from("// Generated by build.rs from assets/syntax/*.packdump; do not edit.\nstatic BUNDLED_SYNTAXES: &[(&str, &[u8])] = &[\n");
    for t in &dumps {
        src.push_str(&format!(
            "    (\"{t}\", include_bytes!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/assets/syntax/{t}.packdump\"))),\n"
        ));
    }
    src.push_str("];\n");
    let out = Path::new(&std::env::var("OUT_DIR").expect("OUT_DIR")).join("bundled_syntaxes.rs");
    fs::write(&out, src).expect("write generated file");
    println!("cargo:rustc-cfg=bundled_syntaxes");
}
