        let rss0 = rss_mb();
        let t = Instant::now();
        let _ = two_face::syntax::extra_no_newlines();
        println!("set load {:?}, rss {:.1} -> {:.1} MB", t.elapsed(), rss0, rss_mb());
        #[cfg_attr(not(bundled_syntaxes), allow(unused_mut))]
        let mut samples: Vec<(&str, String)> = [("rust", "sample.rs"), ("bash", "sample.sh")]
            .iter()
            .map(|(a, b)| (*a, b.to_string()))
            .collect();
        #[cfg(bundled_syntaxes)]
        for (t, _) in BUNDLED_SYNTAXES {
            samples.push((t, format!("sample.{t}")));
        }
